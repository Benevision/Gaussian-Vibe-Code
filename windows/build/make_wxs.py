"""Write the WiX v5 source for the SplatWork for Windows MSI from the bundle folder (docs/dev/WINDOWS.md).

    python windows/build/make_wxs.py --bundle dist/SplatWork --version 1.2.1 --out dist/SplatWork.wxs
    wix build -arch x64 -ext WixToolset.Firewall.wixext -ext WixToolset.UI.wixext dist/SplatWork.wxs -o SplatWork.msi

* per-machine install to ``C:\\Program Files\\SplatWork`` (one UAC prompt), Start-menu shortcut;
* firewall: inbound TCP 7878 (the worker) and UDP 5353 (Bonjour / mDNS) on **Private** networks only, by port,
  because the listening process may be the downloaded GPU runtime's ``python.exe``;
* major upgrade on every version (same UpgradeCode): the GPU runtime, settings and projects live in the user's
  profile and are kept.
"""

from __future__ import annotations

import argparse
import hashlib
import re
from pathlib import Path
from xml.sax.saxutils import quoteattr

# Never change: Windows uses it to find earlier versions for upgrades.
UPGRADE_CODE = "6B3F0E5C-2A4D-4C1E-9E57-5A1D3C8B7F42"
WORKER_PORT = 7878


def ident(prefix: str, rel: str) -> str:
    """A stable WiX identifier (≤ 72 chars) for a relative path."""
    h = hashlib.sha1(rel.lower().encode()).hexdigest()[:16]
    stem = re.sub(r"[^A-Za-z0-9_]", "_", rel)[-40:]
    return f"{prefix}{h}_{stem}"


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--bundle", required=True)
    ap.add_argument("--version", required=True)
    ap.add_argument("--out", required=True)
    a = ap.parse_args()
    bundle = Path(a.bundle).resolve()
    version = re.match(r"\d+\.\d+\.\d+", a.version).group(0)

    lines = []
    w = lines.append

    def walk(d: Path, indent: str) -> None:
        for sub in sorted(p for p in d.iterdir() if p.is_dir()):
            rel = sub.relative_to(bundle).as_posix()
            w(f'{indent}<Directory Id="{ident("d", rel)}" Name={quoteattr(sub.name)}>')
            walk(sub, indent + "  ")
            w(f"{indent}</Directory>")
        for f in sorted(p for p in d.iterdir() if p.is_file()):
            rel = f.relative_to(bundle).as_posix()
            cid = ident("c", rel)
            w(f'{indent}<Component Id="{cid}" Bitness="always64">')
            w(f'{indent}  <File Id="{ident("f", rel)}" Source={quoteattr(str(f))} KeyPath="yes" />')
            w(f"{indent}</Component>")
            comps.append(cid)

    comps: list = []
    walk(bundle, "        ")
    files_xml = "\n".join(lines)
    refs = "\n".join(f'      <ComponentRef Id="{c}" />' for c in comps)
    exe_id = ident("f", "bin/SplatWork.exe")
    icon = Path(__file__).resolve().parents[1] / "branding" / "SplatWork.ico"
    rtf = Path(a.out).resolve().with_name("license.rtf")
    text = (bundle / "LICENSE").read_text(encoding="utf-8")
    esc = text.replace("\\", "\\\\").replace("{", "\\{").replace("}", "\\}").replace("\n", "\\par\n")
    rtf.write_text("{\\rtf1\\ansi\\deff0{\\fonttbl{\\f0 Segoe UI;}}\\fs18 " + esc + "}", encoding="ascii", errors="replace")

    wxs = f"""<?xml version="1.0" encoding="utf-8"?>
<!-- Generated by windows/build/make_wxs.py; do not edit. -->
<Wix xmlns="http://wixtoolset.org/schemas/v4/wxs"
     xmlns:fire="http://wixtoolset.org/schemas/v4/wxs/firewall"
     xmlns:ui="http://wixtoolset.org/schemas/v4/wxs/ui">
  <Package Name="SplatWork" Manufacturer="SplatWork" Version="{version}" UpgradeCode="{UPGRADE_CODE}"
           Scope="perMachine" Compressed="yes" InstallerVersion="500">
    <MajorUpgrade DowngradeErrorMessage="A newer version of SplatWork is already installed." AllowSameVersionUpgrades="yes" />
    <MediaTemplate EmbedCab="yes" CompressionLevel="high" />
    <Icon Id="SplatWorkIcon" SourceFile={quoteattr(str(icon))} />
    <Property Id="ARPPRODUCTICON" Value="SplatWorkIcon" />
    <Property Id="ARPURLINFOABOUT" Value="https://github.com/Benevision/SplatWork" />
    <Property Id="WIXUI_INSTALLDIR" Value="INSTALLFOLDER" />
    <ui:WixUI Id="WixUI_InstallDir" />
    <WixVariable Id="WixUILicenseRtf" Value={quoteattr(str(rtf))} />

    <StandardDirectory Id="ProgramFiles64Folder">
      <Directory Id="INSTALLFOLDER" Name="SplatWork">
{files_xml}
      </Directory>
    </StandardDirectory>
    <StandardDirectory Id="ProgramMenuFolder" />

    <Component Id="StartMenuShortcut" Directory="ProgramMenuFolder" Guid="9C2E7A41-5B3D-4F60-8A1E-2D7C4B9E0F13">
      <Shortcut Id="SplatWorkShortcut" Name="SplatWork" Description="Gaussian splats: capture, train, view"
                Target="[#{exe_id}]" WorkingDirectory="INSTALLFOLDER" Icon="SplatWorkIcon">
        <ShortcutProperty Key="System.AppUserModel.ID" Value="SplatWork.SplatWork" />
      </Shortcut>
      <RegistryValue Root="HKLM" Key="Software\\SplatWork" Name="StartMenuShortcut" Type="integer" Value="1" KeyPath="yes" />
    </Component>

    <Component Id="Firewall" Directory="INSTALLFOLDER" Guid="E1A4C6B2-7D35-4E8F-9B20-3C5D7A1F8E64">
      <fire:FirewallException Id="FwWorker" Name="SplatWork worker (TCP {WORKER_PORT})" Port="{WORKER_PORT}" Protocol="tcp"
                              Scope="localSubnet" Profile="private" Description="Lets Macs on this network send jobs to SplatWork" />
      <fire:FirewallException Id="FwMdns" Name="SplatWork discovery (Bonjour, UDP 5353)" Port="5353" Protocol="udp"
                              Scope="localSubnet" Profile="private" Description="Lets Macs on this network find SplatWork" />
      <RegistryValue Root="HKLM" Key="Software\\SplatWork" Name="Firewall" Type="integer" Value="1" KeyPath="yes" />
    </Component>

    <Feature Id="Main" Title="SplatWork" Level="1">
{refs}
      <ComponentRef Id="StartMenuShortcut" />
      <ComponentRef Id="Firewall" />
    </Feature>
  </Package>
</Wix>
"""
    Path(a.out).write_text(wxs, encoding="utf-8")
    print(f"{a.out}: {len(comps)} files, version {version}")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
